library ieee;
use ieee.std_logic_1164.all;

library work;
use work.misc.all;

-- sn74124 is actually a dual VCO.  In CADR it is used as a single
-- fixed-frequency oscillator, so only the enable and output of one half are
-- modelled.
--
-- The frequency is set by an external capacitor, so it belongs to the socket
-- rather than to the part and the dip wrapper supplies it.  REQTIM 0A01 is
-- the only instance on the boards cadr4 models.
--
-- The part is TI's SN74LS124.  Its data sheet is bulletin DL-S 7612025,
-- March 1974 revised October 1976, in The TTL Data Book for Design Engineers,
-- 2nd edition, section 7, pages 7-123..7-128.  TI deleted the LS part later --
-- the 1981 supplement removes every reference to it and the 1981 edition says
-- it "has been replaced by the SN54LS629 and SN74LS629" -- so a search finds
-- only the S part, and doc/ttl/sn74124.pdf is that S part, not this one.
--
-- Three properties come from the LS sheet, and the S differs on all three:
--
-- The period.  fo = 1e-4 / Cext for the 'LS124 against 5e-4 / Cext for the
-- 'S124, but the sheet gives that "under the conditions used in Figure 3",
-- which are VI(freq) = VI(rng) = 2 V.  REQTIM's 100 pF (reqtim.drw) would be
-- 1 MHz there, but busint.wlr puts A01-02 (CONT) and A01-03 (RNG) on the
-- +5.0V net, and Figure 4 normalises to fn = 1.15..1.18 at 5 V, so 850 ns.
-- The honest band is 0.7..1.0 us: the formula is a typical value, and where
-- it can be checked against MIT's own figure -- DCTMOT 0B04, whose four
-- control pins all sit on a 2V net, so Figure 3's conditions exactly -- its
-- 220 pF section gives 2.20 us against a drawn "PERIOD = 1.8 - 2.0 usec.".
--
-- The idle level.  "While the enable input is low, the output is enabled.
-- While the enable input is high, the output is high."
--
-- The phase.  "The internal oscillator of the 'LS124 runs continuously even
-- while the output is disabled, whereas the internal oscillator of the 'S124
-- is itself started and stopped by the enable input."  tPHL, the only
-- switching parameter the LS is given, is the delay from the enable to the
-- first HIGH-to-LOW output edge, footnoted "30 ns plus up to one period of
-- one cycle ... depending upon the timing of the enable pulse with respect to
-- the signal generated by the internal oscillator".  So the first edge after
-- an enable is a fall, up to a whole period later, and its phase is the
-- oscillator's.  The 30 ns is a propagation delay and cadr4 is not a timing
-- model, so only the phase term is modelled; free running from time zero
-- keeps that phase arbitrary with respect to the enable yet reproducible
-- across runs.
--
-- MIT's rom/mit/cadr1/reqtim.prom assumes "Roughly 2 uSec clock intervals"
-- and labels its table 10, 20 and 26 uSec, which this period does not
-- produce.  Those labels fit the board after doc/ai/cadr1/busint.eco item 5
-- of 2/21/81, which replaces this part with a 74S124 and the capacitor with
-- 1000 pF: 5e-4 / 1e-9 is exactly 2.000 us.  cadr4 models the drawing, which
-- is before that change -- reqtim.drw is 10-DEC-80, busint.wlr 11-DEC-80, and
-- busint.prt, printed 25-MAR-81, a month after the ECO, still stuffs a
-- 74LS124 at A01.

entity sn74124 is
  generic (period : time := 850 ns);
  port (
    en_n : in  std_logic; -- Pin 6 (-1EN)
    y    : out std_logic  -- Pin 7 (1Y)
  );
end entity;


architecture behavioral of sn74124 is
  signal en_n_i : std_logic;
  -- the internal oscillator, which runs whether the output is enabled or not
  signal osc    : std_logic := '0';
  -- the enable, taken by the synchronisation gating
  signal gated  : std_logic := '0';
  constant half_period : time := period / 2;
begin
  en_n_i <= ttl_input(en_n);

  oscillator : process
  begin
    wait for half_period;
    osc <= not osc;
  end process;

  -- "The pulse synchronization-gating section ensures that the first output
  -- pulse is neither clipped nor extended", so the enable is taken at a
  -- falling edge of the oscillator and the first low pulse is full width.
  -- That is also what puts the first output edge up to one period after the
  -- enable, depending on where the oscillator happens to be.
  sync : process (osc, en_n_i)
  begin
    if en_n_i /= '0' then
      gated <= '0';
    elsif falling_edge(osc) then
      gated <= '1';
    end if;
  end process;

  y <= osc when gated = '1' else '1';
end architecture;
