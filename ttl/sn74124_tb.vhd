library ieee;
use ieee.std_logic_1164.all;

use std.env.finish;

use work.sn74.sn74124;

entity sn74124_tb is
end entity;

-- The behaviour pinned here is TI's, from the SN54LS124/SN54S124/SN74LS124/
-- SN74S124 sheet, bulletin DL-S 7612025, March 1974 revised October 1976, in
-- The TTL Data Book for Design Engineers, 2nd edition, section 7, pages
-- 7-123..7-128.  TI later deleted the LS part -- the 1981 supplement removes
-- all references to it and the 1981 edition says it "has been replaced by the
-- SN54LS629 and SN74LS629" -- so doc/ttl/sn74124.pdf is the S part and the LS
-- sheet survives only in the 1976 book.  Three properties come from it:
--
--   "While the enable input is low, the output is enabled.  While the enable
--   input is high, the output is high."
--
--   "The internal oscillator of the 'LS124 runs continuously even while the
--   output is disabled, whereas the internal oscillator of the 'S124 is
--   itself started and stopped by the enable input."
--
--   tPHL, the only switching parameter the LS is given, is the delay from the
--   enable to the first HIGH-to-LOW output edge, footnoted "30 ns plus up to
--   one period of one cycle ... depending upon the timing of the enable pulse
--   with respect to the signal generated by the internal oscillator".
--
-- So the output idles high, the first edge after an enable is a FALL, and its
-- phase is set by the free-running oscillator rather than by the enable.  The
-- 30 ns is a propagation delay and cadr4 is not a timing model, so only the
-- phase term is modelled.

architecture testbench of sn74124_tb is

  -- REQTIM 0A01 is the part's only instance on the boards cadr4 models, and
  -- the period is a property of its socket: 100 pF (doc/ai/cadr1/reqtim.drw)
  -- with both frequency-control pins strapped to +5 (doc/ai/cadr1/busint.wlr,
  -- the +5.0V net carries A01-02 CONT and A01-03 RNG).  fo = 1e-4 / Cext is
  -- 1 MHz, but the sheet states that only "under the conditions used in
  -- Figure 3", which are VI(freq) = VI(rng) = 2 V; Figure 4 normalises to
  -- fn = 1.15..1.18 at 5 V, giving 850 ns.  This value must match the default
  -- in the GENERATED package ttl/sn74.vhd, which is what instantiation binds.
  constant period_d : time := 850 ns;

  -- two instances at a round period, enabled at different times, to show the
  -- phase belongs to the oscillator and not to the enable
  constant period_p : time := 1000 ns;
  constant period_f : time := 100 ns;

  constant t_en_d : time := 200 ns;
  constant t_en_a : time := 100 ns;
  constant t_en_b : time := 350 ns;
  constant t_en_f : time := 3020 ns;

  signal en_n_d : std_logic := '1';
  signal y_d    : std_logic;
  signal en_n_a : std_logic := '1';
  signal y_a    : std_logic;
  signal en_n_b : std_logic := '1';
  signal y_b    : std_logic;
  signal en_n_f : std_logic := '1';
  signal y_f    : std_logic;

  signal t_fall1_d : time := 0 ns;
  signal t_fall2_d : time := 0 ns;
  signal t_fall_a  : time := 0 ns;
  signal t_fall_b  : time := 0 ns;
  signal t_fall_f  : time := 0 ns;

begin

  -- no generic map: this instance pins the package default
  uut_default : sn74124 port map (
    en_n => en_n_d,
    y    => y_d
    );

  uut_a : sn74124
    generic map (period => period_p)
    port map (
      en_n => en_n_a,
      y    => y_a
      );

  uut_b : sn74124
    generic map (period => period_p)
    port map (
      en_n => en_n_b,
      y    => y_b
      );

  uut_fast : sn74124
    generic map (period => period_f)
    port map (
      en_n => en_n_f,
      y    => y_f
      );

  -- the REQTIM state machine counts output edges, so where they fall is the
  -- whole of the timeout behaviour
  stamp_d : process (y_d)
    variable n : natural := 0;
  begin
    if falling_edge(y_d) then
      n := n + 1;
      if n = 1 then
        t_fall1_d <= now;
      elsif n = 2 then
        t_fall2_d <= now;
      end if;
    end if;
  end process;

  stamp_a : process (y_a)
  begin
    if falling_edge(y_a) and t_fall_a = 0 ns then
      t_fall_a <= now;
    end if;
  end process;

  stamp_b : process (y_b)
  begin
    if falling_edge(y_b) and t_fall_b = 0 ns then
      t_fall_b <= now;
    end if;
  end process;

  stamp_f : process (y_f)
  begin
    if falling_edge(y_f) and t_fall_f = 0 ns then
      t_fall_f <= now;
    end if;
  end process;

  process
  begin

    -- Test 1: the output idles HIGH while disabled, on every instance
    wait for 50 ns;
    assert y_d = '1'
      report "Test 1a failed: output should be high while disabled" severity error;
    assert y_a = '1' and y_b = '1' and y_f = '1'
      report "Test 1b failed: every output should be high while disabled" severity error;

    -- enable the three slow instances at three different times
    wait for t_en_a - 50 ns;
    en_n_a <= '0';
    wait for t_en_d - t_en_a;
    en_n_d <= '0';
    wait for t_en_b - t_en_d;
    en_n_b <= '0';

    -- Test 2: the enable does not itself produce an edge.  The oscillator of
    -- uut_a free runs with its falling edges at multiples of period_p, so the
    -- output stays high from the enable at 100 ns until 1000 ns.
    wait for 550 ns;                    -- now 900 ns
    assert y_a = '1'
      report "Test 2a failed: output should stay high until the oscillator falls"
      severity error;
    assert t_fall_a = 0 ns
      report "Test 2b failed: output fell before the oscillator did" severity error;

    -- Test 3: the first edge after the enable is a FALL, and it lands on the
    -- free-running oscillator's edge
    wait for 101 ns;                    -- now 1001 ns
    assert y_a = '0' and y_b = '0'
      report "Test 3a failed: output should be low after the first falling edge"
      severity error;
    assert t_fall_a = period_p
      report "Test 3b failed: first falling edge of uut_a is not at one period"
      severity error;

    -- Test 4: the phase belongs to the oscillator, not to the enable.  Two
    -- instances of the same period enabled 250 ns apart fall at the SAME
    -- absolute time, so their enable-to-first-edge delays differ.  This is
    -- what tPHL's footnote describes and what a model whose first edge
    -- coincides with the enable cannot reproduce.
    assert t_fall_a = t_fall_b
      report "Test 4a failed: the two instances should fall at the same time"
      severity error;
    assert t_fall_a - t_en_a /= t_fall_b - t_en_b
      report "Test 4b failed: the enable-to-edge delay should depend on phase"
      severity error;
    assert t_fall_a - t_en_a > 0 ns and t_fall_a - t_en_a <= period_p
      report "Test 4c failed: uut_a enable-to-edge delay is not within one period"
      severity error;
    assert t_fall_b - t_en_b > 0 ns and t_fall_b - t_en_b <= period_p
      report "Test 4d failed: uut_b enable-to-edge delay is not within one period"
      severity error;

    -- Test 5: once gated through, the output is a square wave of the period
    wait for 498 ns;                    -- now 1499 ns
    assert y_a = '0'
      report "Test 5a failed: output rose before the half period" severity error;
    wait for 2 ns;                      -- now 1501 ns
    assert y_a = '1'
      report "Test 5b failed: output should rise after half a period" severity error;
    wait for 498 ns;                    -- now 1999 ns
    assert y_a = '1'
      report "Test 5c failed: output fell before the full period" severity error;
    wait for 2 ns;                      -- now 2001 ns
    assert y_a = '0'
      report "Test 5d failed: output should fall again after a full period"
      severity error;

    -- Test 6: the package default is period_d.  uut_default was enabled at
    -- 200 ns, so its edges land at 850 ns and 1700 ns.
    assert t_fall1_d = period_d
      report "Test 6a failed: first falling edge is not at the default period"
      severity error;
    assert t_fall2_d - t_fall1_d = period_d
      report "Test 6b failed: the default period is not honoured" severity error;

    -- Test 7: a disable takes the output high at once, whatever the
    -- oscillator is doing (here it is low, so the level actually changes)
    wait for 199 ns;                    -- now 2200 ns
    assert y_a = '0'
      report "Test 7a failed: expected the output low before the disable"
      severity error;
    en_n_a <= '1';
    wait for 1 ns;
    assert y_a = '1'
      report "Test 7b failed: output should go high as soon as it is disabled"
      severity error;
    wait for 399 ns;                    -- now 2600 ns
    assert y_a = '1'
      report "Test 7c failed: output should stay high while disabled" severity error;

    -- Test 8: 'Z' on the enable reads as high, so still disabled
    en_n_a <= 'Z';
    wait for 400 ns;                    -- now 3000 ns
    assert y_a = '1'
      report "Test 8 failed: 'Z' on enable should keep the output high" severity error;

    -- Test 9: the period generic is honoured, and the same phase rule applies
    -- at a different period.  Enabled at 3020 ns, the 100 ns oscillator falls
    -- next at 3100 ns.
    wait for t_en_f - 3000 ns;          -- now 3020 ns
    en_n_f <= '0';
    wait for 79 ns;                     -- now 3099 ns
    assert y_f = '1'
      report "Test 9a failed: fast instance fell before its oscillator did"
      severity error;
    wait for 2 ns;                      -- now 3101 ns
    assert y_f = '0'
      report "Test 9b failed: fast instance should fall at 3100 ns" severity error;
    assert t_fall_f = 3100 ns
      report "Test 9c failed: fast instance first edge is not on the oscillator"
      severity error;
    wait for 48 ns;                     -- now 3149 ns
    assert y_f = '0'
      report "Test 9d failed: fast instance rose before its half period" severity error;
    wait for 2 ns;                      -- now 3151 ns
    assert y_f = '1'
      report "Test 9e failed: fast instance should rise after half a period"
      severity error;

    -- the oscillators free run, so the testbench must end explicitly
    finish;

  end process;

end architecture;
